"""The one-command Vouch demo.

It runs the real service against an in-memory Switch room and produces the same
artifacts the real integration produces. The only simulated part is the
transport: human messages arrive from a script instead of Slack or Teams.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, date, datetime, time
from pathlib import Path

from rich.console import Console
from rich.markdown import Markdown
from rich.panel import Panel
from rich.rule import Rule

from vouch.service import VouchPaths, VouchService, fixed_clock
from vouch.switch.clerk import Clerk
from vouch.switch.fake import FakeSwitch


def _table(headers: list[str], rows: list[list[str]]) -> str:
    def clean(value: str) -> str:
        return value.replace("|", "\\|").replace("\n", " ")

    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines += ["| " + " | ".join(clean(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


@dataclass
class Transcript:
    parts: list[str] = field(default_factory=list)

    def add(self, markdown: str) -> None:
        self.parts.append(markdown.strip() + "\n")

    def render(self, console: Console) -> None:
        console.print(Markdown(self.parts[-1]))

    def write(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            "# Vouch - demo transcript\n\n"
            "_Generated by `vouch demo`. Timestamps are frozen at 2026-11-04; "
            "the signing key is generated in a temporary directory._\n\n" + "\n".join(self.parts),
            encoding="utf-8",
        )


def run_demo(
    *,
    root: Path,
    home: Path,
    write: Path | None = None,
    console: Console | None = None,
    signer_days: int = 30,
) -> str:
    root = root.resolve()
    home = home.resolve()
    home.mkdir(parents=True, exist_ok=True)
    output = console or Console()
    transcript = Transcript()

    def step(title: str) -> None:
        output.print()
        output.print(Rule(f"[bold #E0A100]{title}[/]", style="#3A4459"))
        transcript.add(f"## {title}")

    def say(markdown: str) -> None:
        output.print(Markdown(markdown))
        transcript.add(markdown)

    paths = VouchPaths.discover(root=root, home=home)
    paths.ensure()
    service = VouchService.open(
        paths,
        now=fixed_clock(datetime.combine(date(2026, 11, 4), time(9, 0), tzinfo=UTC)),
    )
    switch = FakeSwitch()
    deal_room = switch.create_room(
        "room-acme-deal",
        "#deal-acme",
        "Sales, engineering, legal, and the Vouch agents underwrite Acme's promises.",
    )
    delivery_room = switch.create_room(
        "room-acme-delivery",
        "#delivery-acme",
        "Only sealed commitments arrive here.",
    )
    clerk = Clerk(
        service=service,
        client=switch,
        deal_id="acme-2026",
        sales_room_id=deal_room.id,
        delivery_room_id=delivery_room.id,
    )

    output.print(
        Panel.fit(
            "[bold #F7F3E8]VOUCH[/]\n[#E0A100]Every promise, vouched for.[/]\n\n"
            "[#AAB4C8]A commitment-underwriting room where sales, engineering, legal,\n"
            "and four agents turn a nervous yes into a signed receipt.[/]",
            border_style="#1F6F6B",
            padding=(1, 4),
        )
    )
    transcript.add(
        "# Vouch - every promise, vouched for\n\n"
        "A commitment-underwriting room where sales, engineering, legal, and four "
        "agents turn a nervous yes into a signed receipt."
    )

    # ---------------------------------------------------------------- intake
    step("1. A deal walks into the room")
    deal, evidence = service.ingest_fixture("acme")
    switch.human(
        deal_room.id,
        "Priya",
        "Acme will not sign without SSO, a 99.95% SLA, SOC 2 Type II, and 20% off. "
        "Can we just say yes?",
    )
    say(
        f"**{deal.account}** ({deal.id}) is a {deal.currency} "
        f"{deal.annual_list_price:,.0f} renewal at a {deal.cost_ratio_pct:.0f}% cost ratio. "
        "Priya has turned the customer's ask into four claims. No commitment exists yet."
    )
    say(
        _table(
            ["Claim", "Type", "Requested", "Due", "Owner"],
            [
                [
                    claim.id,
                    str(claim.type),
                    claim.requested_text,
                    claim.due.isoformat() if claim.due else "-",
                    claim.owner or "-",
                ]
                for claim in deal.claims
            ],
        )
    )
    switch.post(
        deal_room.id,
        "Scout",
        f"I gathered {len(evidence.items)} dated sources, one per claim. "
        "Every source is hashed and linked to its claim. No evidence, no commitment.",
    )
    say(
        f"**Scout** attached {len(evidence.items)} dated evidence items. "
        "The evidence is typed, sourced, and content-addressed; an assertion in chat is not evidence."
    )

    # --------------------------------------------------------------- assess
    step("2. Actuary prices the promises against policy")
    packet = service.assess(deal.id, note="initial underwriting")
    switch.post(
        deal_room.id,
        "Actuary",
        f"Packet v{packet.version} assessed. Discount is inside the 20% ceiling; "
        "the rest narrows. Packet hash " + packet.packet_hash[:12] + ".",
    )
    rows = [
        [
            decision.claim_id,
            decision.verdict,
            decision.approved_text,
            " ".join(decision.policy_refs),
        ]
        for decision in packet.decisions
    ]
    say(
        f"Packet **v{packet.version}** (`{packet.packet_hash[:16]}...`) is deterministic: "
        "the same deal, policy, and evidence always produce the same decisions."
    )
    say(_table(["Claim", "Verdict", "Approved language", "Policy"], rows))
    say(
        "The Actuary has not approved anything with its own authority. It has produced "
        "**typed commitments** for named humans to accept or reject."
    )

    # ---------------------------------------------------- early approval mistake
    step("3. The team approves too early")
    switch.human(deal_room.id, "Priya", "APPROVE ACME-2026 DISC AS AE")
    switch.human(deal_room.id, "Maya", "APPROVE ACME-2026 DISC AS VP_SALES")
    result = clerk.run_once()
    gate = service.gate(deal.id)
    say(
        "Priya (AE) and Maya (VP Sales) approve the **v"
        f"{packet.version}** discount in the room. The Clerk records exactly two approvals, "
        f"each bound to hash `{packet.packet_hash[:12]}...`."
    )
    say(
        _table(
            ["Approval", "Actor", "Status", "Bound hash"],
            [
                [
                    f"{item.claim_id} / {item.role}",
                    item.actor,
                    item.status,
                    item.packet_hash[:12] + "...",
                ]
                for item in service.approvals(deal.id)
            ],
        )
    )
    say(
        f"The gate is still incomplete - {len(gate.pending)} claim/role approvals remain - "
        "but this is the moment most workflows get dangerous."
    )
    _ = result

    # ------------------------------------------------------------- challenge
    step("4. Examiner breaks the packet")
    packet = service.challenge(deal.id)
    switch.post(
        deal_room.id,
        "Examiner",
        f"BLOCK on packet v{packet.version}. Two independent breaks in the discount: "
        "autonomy ceiling and unit economics. I will not sign this.",
    )
    say(
        "The Examiner is a separate agent with a different job: assume the packet is wrong "
        "and try to prove it. It recomputes the economics instead of trusting the Actuary."
    )
    findings = [
        [item.id, item.severity.upper(), item.claim_id or "-", item.code, item.message]
        for item in packet.findings
    ]
    say(_table(["Finding", "Severity", "Claim", "Code", "Why"], findings))
    say(
        f"**Status: {packet.status}.** 20% is inside the headline ceiling, but above the "
        "15% autonomy line and below the 33% gross-margin floor. The packet may not be sealed."
    )

    # ---------------------------------------------------------------- revise
    step("5. Revision invalidates every earlier approval")
    old_hash = packet.packet_hash
    revised = service.revise(deal.id, note="Examiner remediation")
    switch.post(
        deal_room.id,
        "Clerk",
        f"Packet v{revised.version} created. Earlier approvals targeted "
        f"{old_hash[:12]}... and are stale. Humans must approve the new hash.",
    )
    discount = revised.decision("DISC")
    say(
        f"Policy-constrained remediation narrows the discount to "
        f"**{discount.approved_value.get('discount_pct')}%**. "
        f"The new packet hash is `{revised.packet_hash[:16]}...`."
    )
    stale = [item for item in service.approvals(deal.id) if item.status == "stale"]
    say(
        "Approvals are bound to the commitment hash, not to a person's optimistic memory. "
        f"Both earlier approvals are now **{stale[0].status if stale else 'stale'}**: "
        + ", ".join(f"{item.claim_id}/{item.role} by {item.actor}" for item in stale)
        + ". Re-approval is the control working, not friction."
    )
    say(
        _table(
            ["Claim", "v1", "v2", "What changed"],
            [
                ["SSO", "narrow", revised.decision("SSO").verdict, "beta only, GA not committed"],
                [
                    "SLA",
                    "narrow",
                    revised.decision("SLA").verdict,
                    "99.90% with credits and maintenance language",
                ],
                [
                    "DISC",
                    "approve 20%",
                    f"narrow {discount.approved_value.get('discount_pct')}%",
                    "autonomy + margin",
                ],
                ["SOC2", "narrow", revised.decision("SOC2").verdict, "in progress, not certified"],
            ],
        )
    )

    # --------------------------------------------------------- clean challenge
    step("6. Examiner re-checks the revised packet")
    checked = service.challenge(deal.id)
    switch.post(
        deal_room.id,
        "Examiner",
        f"Packet v{checked.version} is {checked.status}. No blocking findings. "
        "The remaining conditions are part of the commitments.",
    )
    say(
        f"**Status: {checked.status}.** Zero blocking findings. The Examiner's pass is "
        "independent of the Actuary's assessment and of the humans' enthusiasm."
    )

    # ------------------------------------------------------------- approvals
    step("7. Humans approve the exact packet in Switch")
    for actor, body in [
        ("Priya", "APPROVE ACME-2026 SSO AS AE"),
        ("Sam", "APPROVE ACME-2026 SSO AS ENG_LEAD"),
        ("Priya", "APPROVE ACME-2026 SLA AS AE"),
        ("Sam", "APPROVE ACME-2026 SLA AS ENG_LEAD"),
        ("Priya", "APPROVE ACME-2026 DISC AS AE"),
        ("Maya", "APPROVE ACME-2026 DISC AS VP_SALES"),
        ("Priya", "APPROVE ACME-2026 SOC2 AS AE"),
        ("Alex", "APPROVE ACME-2026 SOC2 AS LEGAL"),
    ]:
        switch.human(deal_room.id, actor, body)
    resolved = clerk.run_once()
    gate = service.gate(deal.id)
    say(
        f"Eight approval messages arrive from four named humans. The Clerk records "
        f"{resolved['recorded']} valid approvals against hash `{checked.packet_hash[:12]}...` "
        "and posts the remaining state back to the room."
    )
    say(
        _table(
            ["Claim", "Role", "Actor", "Phrase", "Status"],
            [
                [item.claim_id, item.role, item.actor, f"`{item.phrase}`", item.status]
                for item in service.approvals(deal.id)
                if item.status == "valid"
            ],
        )
    )
    say(
        f"**Gate: {'clear' if gate.ok else 'blocked'}.** "
        + (
            "Every required role has approved this exact hash."
            if gate.ok
            else ", ".join(gate.pending)
        )
    )

    # ------------------------------------------------------------------- seal
    step("8. Clerk seals the receipt")
    switch.human(deal_room.id, "Maya", "VOUCH SEAL")
    clerk.run_once()
    receipt = service.store.latest_receipt(deal.id)
    say(
        f"Receipt **`{receipt.body.receipt_id}`** is issued and signed with Ed25519. "
        "It contains only approved commitments and their conditions."
    )
    say(
        _table(
            ["Claim", "Commitment", "Conditions"],
            [
                [item.claim_id, item.commitment, "; ".join(item.conditions)]
                for item in receipt.body.commitments
            ],
        )
    )
    say(
        f"Body hash `{receipt.body_hash[:24]}...`; signature `{receipt.signature[:24]}...`; "
        f"expires {receipt.body.expires_at.date().isoformat()}."
    )

    # ---------------------------------------------------------------- verify
    step("9. Verification is adversarial, not decorative")
    verification = service.verify(receipt, require_unexpired=True, pinned_key=True)
    say(
        _table(
            ["Check", "Result", "Detail"],
            [
                [item.code, "PASS" if item.ok else "FAIL", item.detail]
                for item in verification.checks
            ],
        )
    )
    tampered = receipt.model_copy(deep=True)
    tampered.body.commitments[0].commitment = "SSO generally available by 2026-11-30."
    broken = service.verify(tampered)
    say(
        f"Now edit one character of an approved commitment and verify again: "
        f"**{'PASS' if broken.ok else 'FAIL'}** - {broken.summary}. "
        "The signed body hash catches it without trusting the database."
    )

    # --------------------------------------------------------------- handoff
    step("10. Only approved commitments cross into delivery")
    handoff = service.handoff_text(deal.id)
    delivery_messages = switch.messages(delivery_room.id)
    say("**#delivery-acme** received this handoff:")
    say("```markdown\n" + handoff + "\n```")
    say(
        "Notice what is **not** there: no 20% discount, no 99.95% SLA, no GA date, "
        "and no claim that SOC 2 is certified. The delivery room cannot accidentally "
        "inherit a promise that was never approved."
    )
    _ = delivery_messages

    # ----------------------------------------------------------------- audit
    step("11. The audit chain closes")
    _, detail = service.store.verify_audit()
    say(
        f"**Audit:** {detail}. Each event chains to the previous one; editing history "
        "breaks verification. The receipt chain also links to the prior receipt for this account."
    )
    say(
        "### What just happened\n"
        "- Four claims, four evidence items, one deterministic policy.\n"
        "- Two early approvals invalidated by a packet revision.\n"
        "- Eight human approvals across four roles, all bound to one hash.\n"
        "- One Examiner block, one revision, zero blocking findings.\n"
        "- One signed receipt, one tamper failure, one clean handoff."
    )

    transcript_text = "\n".join(transcript.parts)
    if write is not None:
        transcript.write(write)
    service.close()
    return transcript_text
