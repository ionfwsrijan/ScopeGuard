"""The one-command Scope Guard demo.

It runs the real service against an in-memory Switch room and produces the same
artifacts the real integration produces. The only simulated part is the
transport: human messages arrive from a script instead of Slack or Teams.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, date, datetime, time
from pathlib import Path

from rich.console import Console
from rich.markdown import Markdown
from rich.panel import Panel
from rich.rule import Rule

from scopeguard.service import ScopePaths, ScopeService, fixed_clock
from scopeguard.switch.clerk import Clerk
from scopeguard.switch.fake import FakeSwitch


def _table(headers: list[str], rows: list[list[str]]) -> str:
    def clean(value: str) -> str:
        return value.replace("|", "\\|").replace("\n", " ")

    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines += ["| " + " | ".join(clean(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


@dataclass
class Transcript:
    parts: list[str] = field(default_factory=list)

    def add(self, markdown: str) -> None:
        self.parts.append(markdown.strip() + "\n")

    def render(self, console: Console) -> None:
        console.print(Markdown(self.parts[-1]))

    def write(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            "# Scope Guard - demo transcript\n\n"
            "_Generated by `scopeguard demo`. The clock is frozen at 2026-11-04; "
            "signing keys are generated in a temporary directory._\n\n" + "\n".join(self.parts),
            encoding="utf-8",
        )


def run_demo(
    *,
    root: Path,
    home: Path,
    write: Path | None = None,
    console: Console | None = None,
    signer_days: int = 30,
) -> str:
    root = root.resolve()
    home = home.resolve()
    home.mkdir(parents=True, exist_ok=True)
    output = console or Console()
    transcript = Transcript()

    def step(title: str) -> None:
        output.print()
        output.print(Rule(f"[bold #E0A100]{title}[/]", style="#3A4459"))
        transcript.add(f"## {title}")

    def say(markdown: str) -> None:
        output.print(Markdown(markdown))
        transcript.add(markdown)

    paths = ScopePaths.discover(root=root, home=home)
    paths.ensure()
    service = ScopeService.open(
        paths,
        now=fixed_clock(datetime.combine(date(2026, 11, 4), time(9, 0), tzinfo=UTC)),
    )
    switch = FakeSwitch()
    scope_room = switch.create_room(
        "room-northwind-scope",
        "#scope-northwind",
        "Changes are priced, challenged, and signed here. Nothing else crosses.",
    )
    delivery_room = switch.create_room(
        "room-northwind-delivery",
        "#delivery-northwind",
        "Only two-party signed change orders arrive here.",
    )
    clerk = Clerk(
        service=service,
        client=switch,
        engagement_id="northwind-2026",
        scope_room_id=scope_room.id,
        delivery_room_id=delivery_room.id,
    )

    output.print(
        Panel.fit(
            "[bold #F7F3E8]SCOPE GUARD[/]\n"
            "[#E0A100]Every 'one more thing' gets a price.[/]\n\n"
            "[#AAB4C8]A change-order room where delivery, finance, and legal price the ask,\n"
            "an independent Red Team attacks the answer, named humans sign the exact hash,\n"
            "and the client countersigns before anything reaches delivery.[/]",
            border_style="#1F6F6B",
            padding=(1, 4),
        )
    )
    transcript.add(
        "# Scope Guard - every 'one more thing' gets a price\n\n"
        "A change-order room where delivery, finance, and legal price the ask, an "
        "independent Red Team attacks the answer, named humans sign the exact hash, and "
        "the client countersigns before anything reaches delivery."
    )

    # ---------------------------------------------------------------- intake
    step("1. A fixed-fee engagement gets four 'small' asks")
    engagement, evidence = service.ingest_fixture("northwind")
    switch.human(
        scope_room.id,
        "Dana",
        "Northwind wants a native mobile app, a two-week pull-in, 20% off the change "
        "order, and unlimited liability. They need an answer today.",
    )
    say(
        f"**{engagement.client}** ({engagement.id}) is a "
        f"{engagement.currency} {engagement.contract_value:,.0f} fixed-fee contract at a "
        f"{engagement.delivery_cost_ratio_pct:.0f}% delivery cost ratio. Launch is "
        "2026-12-15. The margin is already thin."
    )
    say(
        _table(
            ["Request", "Type", "Requested", "Due", "Owner"],
            [
                [
                    request.id,
                    str(request.type),
                    request.requested_text,
                    request.due.isoformat() if request.due else "-",
                    request.owner or "-",
                ]
                for request in engagement.requests
            ],
        )
    )
    switch.post(
        scope_room.id,
        "Scout",
        f"I attached {len(evidence.items)} dated sources, one per request. "
        "Every source is typed, hashed, and linked to its request. No evidence, no price.",
    )
    say(
        f"**Scout** attached {len(evidence.items)} dated evidence items. An assertion in "
        "chat is not evidence; a dated, sourced record is."
    )

    # --------------------------------------------------------------- pricing
    step("2. Pricer turns four asks into four priced decisions")
    packet = service.assess(engagement.id, note="initial change order")
    switch.post(
        scope_room.id,
        "Pricer",
        f"Packet v{packet.version} priced. Subtotal {packet.subtotal:,.2f} "
        f"{packet.currency}, discount {packet.discount_total:,.2f}, total "
        f"{packet.total:,.2f}. Hash {packet.packet_hash[:12]}.",
    )
    say(
        f"Packet **v{packet.version}** (`{packet.packet_hash[:16]}...`) comes from policy "
        "and evidence only. Run it twice and every number is identical."
    )
    say(
        _table(
            ["Request", "Verdict", "Priced language", "Amount"],
            [
                [
                    decision.request_id,
                    decision.verdict,
                    decision.priced_text,
                    f"{decision.amount:+,.2f}" if decision.amount is not None else "-",
                ]
                for decision in packet.decisions
            ],
        )
    )
    say(
        f"**Subtotal {packet.subtotal:,.2f} {packet.currency}; discount "
        f"{packet.discount_total:,.2f}; total {packet.total:,.2f}.** "
        "The Pricer has approved nothing. It produced typed commitments for named humans "
        "to accept or reject."
    )

    # ---------------------------------------------------- early approval mistake
    step("3. The room signs the first price too early")
    switch.human(scope_room.id, "Dana", "SIGN NORTHWIND-2026 RATE AS ACCOUNT_LEAD")
    switch.human(scope_room.id, "Rae", "SIGN NORTHWIND-2026 RATE AS FINANCE")
    clerk.run_once()
    gate = service.gate(engagement.id)
    say(
        "Dana (Account Lead) and Rae (Finance) sign the **v1** rate line. The Clerk binds "
        f"each signature to hash `{packet.packet_hash[:12]}...` and records exactly two."
    )
    say(
        _table(
            ["Signature", "Actor", "Status", "Bound hash"],
            [
                [
                    f"{item.request_id} / {item.role}",
                    item.actor,
                    item.status,
                    item.packet_hash[:12] + "...",
                ]
                for item in service.approvals(engagement.id)
            ],
        )
    )
    say(
        f"The gate is still incomplete - {len(gate.pending)} request/role signatures remain - "
        "but this is the moment most workflows get dangerous."
    )

    # ------------------------------------------------------------- challenge
    step("4. Red Team breaks the packet")
    packet = service.challenge(engagement.id)
    switch.post(
        scope_room.id,
        "Red Team",
        f"BLOCK on packet v{packet.version}. 20% is above autonomy and below the margin "
        "floor. I will not let this hash be sealed.",
    )
    say(
        "The Red Team is a separate agent with a different job: assume the packet is wrong "
        "and try to prove it. It recomputes the economics instead of trusting the Pricer."
    )
    say(
        _table(
            ["Finding", "Severity", "Request", "Code", "Why"],
            [
                [
                    item.id,
                    item.severity.upper(),
                    item.request_id or "-",
                    item.code,
                    item.message,
                ]
                for item in packet.findings
            ],
        )
    )
    rate = packet.decision("RATE")
    say(
        f"**Status: {packet.status}.** 20% is inside the headline ceiling, but above the "
        f"{service.policy.rate.autonomy_pct:.0f}% autonomy line and below the "
        f"{service.policy.rate.margin_floor_pct:.0f}% gross-margin floor "
        f"({rate.approved_value.get('margin_pct')}% at 20%). The packet may not be sealed."
    )

    # ---------------------------------------------------------------- revise
    step("5. Revision invalidates every earlier signature")
    old_hash = packet.packet_hash
    old_total = packet.total
    revised = service.revise(engagement.id, note="Red Team remediation")
    switched = revised.decision("RATE")
    new_total = revised.total
    switch.post(
        scope_room.id,
        "Clerk",
        f"Packet v{revised.version} created. Earlier signatures targeted "
        f"{old_hash[:12]}... and are stale. Humans must sign the new hash.",
    )
    say(
        f"Policy-constrained remediation narrows the discount to "
        f"**{switched.approved_value.get('discount_pct')}%** and adds the cap as a "
        f"condition. The new hash is `{revised.packet_hash[:16]}...`."
    )
    say(
        f"The total moves from **{old_total:,.2f}** to **{new_total:,.2f} "
        f"{revised.currency}**, protecting **{new_total - old_total:,.2f}** of margin. "
        "That is the price of the Red Team, stated in money."
    )
    stale = [item for item in service.approvals(engagement.id) if item.status == "stale"]
    say(
        "Signatures bind to the commitment hash, not to a person's optimistic memory. "
        "Both earlier signatures are now **stale**: "
        + ", ".join(f"{item.request_id}/{item.role} by {item.actor}" for item in stale)
        + ". Re-signing is the control working, not friction."
    )
    say(
        _table(
            ["Request", "v1", "v2", "What changed"],
            [
                [
                    "MOBILE",
                    "narrow",
                    revised.decision("MOBILE").verdict,
                    "beta only; GA is a separate change order",
                ],
                [
                    "RUSH",
                    "narrow",
                    revised.decision("RUSH").verdict,
                    "one week of acceleration, not two",
                ],
                [
                    "RATE",
                    "narrow 20%",
                    f"narrow {switched.approved_value.get('discount_pct')}%",
                    "autonomy ceiling + margin floor",
                ],
                [
                    "TERMS",
                    "narrow",
                    revised.decision("TERMS").verdict,
                    "unlimited liability refused; 2x cap",
                ],
            ],
        )
    )

    # --------------------------------------------------------- clean challenge
    step("6. Red Team re-checks the revised packet")
    checked = service.challenge(engagement.id)
    switch.post(
        scope_room.id,
        "Red Team",
        f"Packet v{checked.version} is {checked.status}. No blocking findings. "
        "The conditions are part of the commitments.",
    )
    say(
        f"**Status: {checked.status}.** Zero blocking findings. The Red Team's pass is "
        "independent of the Pricer's assessment and of the humans' enthusiasm."
    )

    # ------------------------------------------------------------- signatures
    step("7. Named humans sign the exact packet hash")
    for actor, body in [
        ("Dana", "SIGN NORTHWIND-2026 MOBILE AS ACCOUNT_LEAD"),
        ("Marco", "SIGN NORTHWIND-2026 MOBILE AS DELIVERY_LEAD"),
        ("Dana", "SIGN NORTHWIND-2026 RUSH AS ACCOUNT_LEAD"),
        ("Marco", "SIGN NORTHWIND-2026 RUSH AS DELIVERY_LEAD"),
        ("Dana", "SIGN NORTHWIND-2026 RATE AS ACCOUNT_LEAD"),
        ("Rae", "SIGN NORTHWIND-2026 RATE AS FINANCE"),
        ("Dana", "SIGN NORTHWIND-2026 TERMS AS ACCOUNT_LEAD"),
        ("Iris", "SIGN NORTHWIND-2026 TERMS AS LEGAL"),
    ]:
        switch.human(scope_room.id, actor, body)
    resolved = clerk.run_once()
    gate = service.gate(engagement.id)
    say(
        f"Eight signature messages arrive from four named humans. The Clerk records "
        f"{resolved['recorded']} valid signatures against hash "
        f"`{checked.packet_hash[:12]}...` and posts the remaining state back to the room."
    )
    say(
        _table(
            ["Request", "Role", "Actor", "Phrase", "Status"],
            [
                [
                    item.request_id,
                    item.role,
                    item.actor,
                    f"`{item.phrase}`",
                    item.status,
                ]
                for item in service.approvals(engagement.id)
                if item.status == "valid"
            ],
        )
    )
    say(
        f"**Gate: {'clear' if gate.ok else 'blocked'}.** "
        + ("Every required role signed this exact hash." if gate.ok else ", ".join(gate.pending))
    )

    # ------------------------------------------------------------------- seal
    step("8. Clerk seals a two-party change order")
    switch.human(scope_room.id, "Dana", "SCOPE SEAL")
    clerk.run_once()
    receipt = service.store.latest_receipt(engagement.id)
    say(
        f"Change order **`{receipt.body.receipt_id}`** is issued and signed with Ed25519. "
        "It contains only the signed line items and their conditions."
    )
    say(
        _table(
            ["Request", "Scope", "Amount", "Conditions"],
            [
                [
                    item.request_id,
                    item.scope,
                    f"{item.amount:+,.2f}",
                    "; ".join(item.conditions),
                ]
                for item in receipt.body.line_items
            ],
        )
    )
    say(
        f"**Subtotal {receipt.body.subtotal:,.2f}; discount "
        f"{receipt.body.discount_total:,.2f}; total {receipt.body.total:,.2f} "
        f"{receipt.body.currency}.** Body hash `{receipt.body_hash[:24]}...`; "
        f"issuer signature `{receipt.signature[:24]}...`."
    )

    # ----------------------------------------------------------- countersign
    step("9. The client countersigns the change order")
    switch.human(scope_room.id, "Jordan", "SCOPE ACCEPT Jordan Reyes")
    clerk.run_once()
    receipt = service.store.latest_receipt(engagement.id)
    acceptance = receipt.acceptance
    say(
        f"Jordan Reyes (Northwind Health) countersigns `{receipt.body.receipt_id}`. "
        "The acceptance is a second Ed25519 signature over the issuer's body hash, the "
        "issuer name, and the client's public key."
    )
    say(
        _table(
            ["Party", "Signs", "Key", "Signature"],
            [
                [
                    "Scope Guard",
                    "the complete change-order body",
                    f"`{receipt.public_key[:16]}...`",
                    f"`{receipt.signature[:16]}...`",
                ],
                [
                    f"Northwind Health ({acceptance.issuer if acceptance else 'n/a'})",
                    "the issuer's body hash",
                    f"`{acceptance.public_key[:16] if acceptance else ''}...`",
                    f"`{acceptance.signature[:16] if acceptance else ''}...`",
                ],
            ],
        )
    )
    say(
        "A one-party receipt is a promise. A two-party change order is an agreement. "
        "The difference is one more signature and a much stronger story in a dispute."
    )

    # ---------------------------------------------------------------- verify
    step("10. Verification is adversarial, not decorative")
    verification = service.verify(
        receipt,
        require_unexpired=True,
        require_acceptance=True,
        pinned_key=True,
        pinned_client_key=True,
    )
    say(
        _table(
            ["Check", "Result", "Detail"],
            [
                [item.code, "PASS" if item.ok else "FAIL", item.detail]
                for item in verification.checks
            ],
        )
    )
    tampered = receipt.model_copy(deep=True)
    tampered.body.line_items[0].scope = "Native mobile app, generally available 2026-12-15."
    tampered.body.total = tampered.body.total + 1000
    broken = service.verify(tampered)
    say(
        "Now edit one character of an approved scope line and verify again: "
        f"**{'PASS' if broken.ok else 'FAIL'}** - {broken.summary}. "
        "The signed body hash catches it without trusting the database."
    )

    # --------------------------------------------------------------- handoff
    step("11. Only the signed change order crosses into delivery")
    handoff = service.handoff_text(engagement.id)
    delivery_messages = switch.messages(delivery_room.id)
    say("**#delivery-northwind** received this handoff:")
    say("```markdown\n" + handoff + "\n```")
    say(
        "Notice what is **not** there: no GA date, no two-week acceleration, no 20% "
        "discount, and no unlimited liability. Delivery cannot accidentally inherit a "
        "promise that was never signed."
    )
    _ = delivery_messages

    # ----------------------------------------------------------------- audit
    step("12. The audit chain closes")
    _, detail = service.store.verify_audit()
    say(
        f"**Audit:** {detail}. Each event chains to the previous one; editing history "
        "breaks verification. The change order also links to the previous change order "
        "for this engagement."
    )
    say(
        "### What just happened\n"
        "- Four requests, four dated evidence items, one deterministic policy.\n"
        "- Two early signatures invalidated by a priced revision.\n"
        "- Eight human signatures across four roles, all bound to one hash.\n"
        "- One Red Team block, one revision, zero blocking findings.\n"
        "- One two-party signed change order, one tamper failure, one clean handoff."
    )

    transcript_text = "\n".join(transcript.parts)
    if write is not None:
        transcript.write(write)
        (write.parent / "receipt.json").write_text(
            receipt.model_dump_json(indent=2), encoding="utf-8"
        )
    service.close()
    return transcript_text
